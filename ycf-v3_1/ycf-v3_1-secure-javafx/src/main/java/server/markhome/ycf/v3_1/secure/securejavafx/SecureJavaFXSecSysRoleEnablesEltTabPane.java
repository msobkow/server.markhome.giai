/**
 *	SecureJavaFXSecSysRoleEnablesEltTabPane JavaFX Element TabPane implementation
 *	for SecSysRoleEnables.
 */
public class SecureJavaFXSecSysRoleEnablesEltTabPane
extends CFTabPane
implements ISecureJavaFXSecSysRoleEnablesPaneCommon
{
	protected ICFFormManager cfFormManager = null;
	protected ISecureJavaFXSchema javafxSchema = null;
	protected boolean javafxIsInitializing = true;

	public SecureJavaFXSecSysRoleEnablesEltTabPane( ICFFormManager formManager, ISecureJavaFXSchema argSchema, ISecureSecSysRoleEnablesObj argFocus ) {
		super();
		final String S_ProcName = "construct-schema-focus";
		if( formManager == null ) {
			throw new CFLibNullArgumentException( getClass(),
				S_ProcName,
				1,
				"formManager" );
		}
		cfFormManager = formManager;
		if( argSchema == null ) {
			throw new CFLibNullArgumentException( getClass(),
				S_ProcName,
				2,
				"argSchema" );
		}
		// argFocus is optional; focus may be set later during execution as
		// conditions of the runtime change.
		javafxSchema = argSchema;
		setJavaFXFocusAsSecSysRoleEnables( argFocus );
		// Wire the newly constructed Panes/Tabs to this TabPane
		javafxIsInitializing = false;
	}

	public ICFFormManager getCFFormManager() {
		return( cfFormManager );
	}

	public void setCFFormManager( ICFFormManager value ) {
		final String S_ProcName = "setCFFormManager";
		if( value == null ) {
			throw new CFLibNullArgumentException( getClass(),
				S_ProcName,
				1,
				"value" );
		}
		cfFormManager = value;
	}

	public ISecureJavaFXSchema getJavaFXSchema() {
		return( javafxSchema );
	}

	public void setJavaFXFocus( ICFLibAnyObj value ) {
		final String S_ProcName = "setJavaFXFocus";
		if( ( value == null ) || ( value instanceof ISecureSecSysRoleEnablesObj ) ) {
			super.setJavaFXFocus( value );
		}
		else {
			throw new CFLibUnsupportedClassException( getClass(),
				S_ProcName,
				"value",
				value,
				"ISecureSecSysRoleEnablesObj" );
		}
	}

	public void setJavaFXFocusAsSecSysRoleEnables( ISecureSecSysRoleEnablesObj value ) {
		setJavaFXFocus( value );
	}

	public ISecureSecSysRoleEnablesObj getJavaFXFocusAsSecSysRoleEnables() {
		return( (ISecureSecSysRoleEnablesObj)getJavaFXFocus() );
	}

	public void setPaneMode( CFPane.PaneMode value ) {
		CFPane.PaneMode oldMode = getPaneMode();
		super.setPaneMode( value );
	}
}
