/*
 *	YCFBamXmlLoaderLicenseParse XML SAX Element Handler implementation
 *	for License.
 */
public class YCFBamXmlLoaderLicenseHandler
	extends YCFLibXmlCoreElementHandler
{
	public YCFBamXmlLoaderLicenseHandler( YCFBamXmlLoader saxLoader ) {
		super( saxLoader );
	}

	public void startElement(
		String		uri,
		String		localName,
		String		qName,
		Attributes	attrs )
	throws SAXException
	{
		try {
			// Common XML Attributes
			String	attrId = null;
			// License Attributes
			String	attrName = null;
			String	attrDescription = null;
			String	attrFullText = null;
			// License References
			IYCFBamTenantObj refTenant = null;
			IYCFBamTopDomainObj refDomain = null;
			// Attribute Extraction
			String	attrLocalName;
			int		numAttrs;
			int		idxAttr;
			final String S_ProcName = "startElement";
			final String S_LocalName = "LocalName";

			assert qName.equals( "License" );

			YCFBamXmlLoader saxLoader = (YCFBamXmlLoader)getParser();
			if( saxLoader == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser()" );
			}

			IYCFBamSchemaObj schemaObj = saxLoader.getSchemaObj();
			if( schemaObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"getParser().getSchemaObj()" );
			}

			// Instantiate an edit buffer for the parsed information
			IYCFBamLicenseEditObj editBuff = (IYCFBamLicenseEditObj)schemaObj.getLicenseTableObj().newInstance().beginEdit();

			// Extract Attributes
			numAttrs = attrs.getLength();
			for( idxAttr = 0; idxAttr < numAttrs; idxAttr++ ) {
				attrLocalName = attrs.getLocalName( idxAttr );
				if( attrLocalName.equals( "Id" ) ) {
					if( attrId != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrId = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "Name" ) ) {
					if( attrName != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrName = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "Description" ) ) {
					if( attrDescription != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrDescription = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "FullText" ) ) {
					if( attrFullText != null ) {
						throw new YCFLibUniqueIndexViolationException( getClass(),
							S_ProcName,
							S_LocalName,
							attrLocalName );
					}
					attrFullText = attrs.getValue( idxAttr );
				}
				else if( attrLocalName.equals( "schemaLocation" ) ) {
					// ignored
				}
				else {
					throw new YCFLibUnrecognizedAttributeException( getClass(),
						S_ProcName,
						getParser().getLocationInfo(),
						attrLocalName );
				}
			}

			// Ensure that required attributes have values
			if( attrName == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"Name" );
			}

			// Save named attributes to context
			YCFLibXmlCoreContext curContext = getParser().getCurContext();
			curContext.putNamedValue( "Id", attrId );
			curContext.putNamedValue( "Name", attrName );
			curContext.putNamedValue( "Description", attrDescription );
			curContext.putNamedValue( "FullText", attrFullText );

			// Convert string attributes to native Cafe types
			// and apply the converted attributes to the editBuff.

			Integer natId;
			if( ( attrId != null ) && ( attrId.length() > 0 ) ) {
				natId = Integer.valueOf( Integer.parseInt( attrId ) );
			}
			else {
				natId = null;
			}
			String natName = attrName;
			editBuff.setRequiredName( natName );

			String natDescription = attrDescription;
			editBuff.setOptionalDescription( natDescription );

			String natFullText = attrFullText;
			editBuff.setOptionalFullText( natFullText );

			// Get the scope/container object

			YCFLibXmlCoreContext parentContext = curContext.getPrevContext();
			Object scopeObj;
			if( parentContext != null ) {
				scopeObj = parentContext.getNamedValue( "Object" );
			}
			else {
				scopeObj = null;
			}

			// Resolve and apply required Container reference

			if( scopeObj == null ) {
				throw new YCFLibNullArgumentException( getClass(),
					S_ProcName,
					0,
					"scopeObj" );
			}
			else if( scopeObj instanceof IYCFBamTopDomainObj ) {
				refDomain = (IYCFBamTopDomainObj) scopeObj;
				editBuff.setRequiredContainerTopDomain( refDomain );
				refTenant = (IYCFBamTenantObj)editBuff.getRequiredOwnerTenant();
			}
			else {
				throw new YCFLibUnsupportedClassException( getClass(),
					S_ProcName,
					"scopeObj",
					scopeObj,
					"IYCFBamDomainObj" );
			}

			// Resolve and apply Owner reference

			if( refTenant == null ) {
				if( scopeObj instanceof IYCFBamTenantObj ) {
					refTenant = (IYCFBamTenantObj) scopeObj;
					editBuff.setRequiredOwnerTenant( refTenant );
				}
				else {
					throw new YCFLibNullArgumentException( getClass(),
						S_ProcName,
						0,
						"Owner<Tenant>" );
				}
			}

			IYCFBamLicenseEditObj editLicense = null;
			IYCFIntLicenseObj origLicense = schemaObj.getLicenseTableObj().readLicenseByUNameIdx( refTenant.getRequiredId(),
			refDomain.getRequiredId(),
			editBuff.getRequiredName() );
			if( origLicense == null ) {
				editLicense = editBuff;
			}

			if( editLicense != null ) {
				if( origLicense != null ) {
					editLicense.update();
				}
				else {
					origLicense = (IYCFIntLicenseObj)editLicense.create();
				}
				editLicense = null;
			}

			curContext.putNamedValue( "Object", origLicense );
		}
		catch( RuntimeException e ) {
			throw new RuntimeException( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getSimpleName() + " - " + e.getMessage(),
				e );
		}
		catch( Error e ) {
			throw new Error( "Near " + getParser().getLocationInfo() + ": Caught and rethrew " + e.getClass().getSimpleName() + " - " + e.getMessage(),
				e );
		}
	}

	public void endElement(
		String		uri,
		String		localName,
		String		qName )
	throws SAXException
	{
		final String S_ProcName = "endElement";

		assert qName.equals( "License" );

		YCFLibXmlCoreContext curContext = getParser().getCurContext();

		IYCFBamLicenseObj license;
		if( curContext != null ) {
			license = (IYCFBamLicenseObj)curContext.getNamedValue( "Object" );
		}
		else {
			throw new YCFLibRuntimeException( getClass(),
				S_ProcName,
				"Context must be an existing License element" );
		}

		String text = curContext.getElementText();

		IYCFBamLicenseEditObj editLicense = (IYCFBamLicenseEditObj)license.beginEdit();
		editLicense.setOptionalEmbeddedText( text );
		editLicense.update();
		editLicense = null;
	}
}
